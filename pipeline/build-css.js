// pipeline/build-css.js
// Goal: turn tokens.json into tokens.css (a list of CSS variables),
// and also copy it into the React app so the app can import it.

const fs = require('fs');
const path = require('path');

// Input: the clean tokens. Outputs: the CSS file, and a copy for the app.
const tokensPath = path.join(__dirname, '..', 'output', 'tokens.json');
const cssPath = path.join(__dirname, '..', 'output', 'tokens.css');
const appCssPath = path.join(__dirname, '..', 'demo-app', 'src', 'tokens.css');

// Read tokens.json and turn the text into an object.
const tokens = JSON.parse(fs.readFileSync(tokensPath, 'utf8'));

// 'lines' collects each line of the CSS file, in order.
const lines = [];
lines.push('/* AUTO-GENERATED by pipeline/build-css.js. Do not edit by hand. */');
lines.push(':root {');

// Colors: one variable per color, e.g. --color-primary: #1d4ed8;
lines.push('  /* Colors */');
for (const [name, hex] of Object.entries(tokens.color)) {
  lines.push(`  --color-${name}: ${hex};`);
}

// Typography: four variables per text style (family, size, weight, line height).
lines.push('');
lines.push('  /* Typography */');
for (const [name, f] of Object.entries(tokens.font)) {
  lines.push(`  --font-${name}-family: "${f.family}", system-ui, sans-serif;`);
  lines.push(`  --font-${name}-size: ${f.size}px;`);
  lines.push(`  --font-${name}-weight: ${f.weight};`);
  lines.push(`  --font-${name}-line-height: ${f.lineHeight}px;`);
}

// Spacing: one variable per step, e.g. --space-md: 16px;
lines.push('');
lines.push('  /* Spacing (defined by hand, not read from Figma) */');
for (const [name, px] of Object.entries(tokens.spacing)) {
  lines.push(`  --space-${name}: ${px}px;`);
}

lines.push('}');

// Join all lines with line breaks.
const css = lines.join('\n') + '\n';

// Save the file in output/ and a copy inside the React app.
fs.writeFileSync(cssPath, css);
fs.writeFileSync(appCssPath, css);
console.log('Saved output/tokens.css with', lines.length, 'lines');
console.log('Copied to demo-app/src/tokens.css');